package proto

import (
	"bytes"
	"encoding/base64"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"strings"
)

// Vectors is the schema of proto/vectors.json, shared with the Android unit tests.
type Vectors struct {
	Comment     string          `json:"comment"`
	Protocol    string          `json:"protocol"`
	AAD         string          `json:"aad"`
	SecretHex   string          `json:"secret_hex"`
	Code        string          `json:"code"`
	DisplayCode string          `json:"display_code"`
	QRText      string          `json:"qr_text"`
	KeyHex      string          `json:"key_hex"`
	Topic       string          `json:"topic"`
	Messages    []MessageVector `json:"messages"`
	CodeInputs  []CodeVector    `json:"code_inputs"`
	Invalid     []InvalidVector `json:"invalid_sealed"`
}

// MessageVector is one sealed message.
type MessageVector struct {
	Name          string          `json:"name"`
	Type          string          `json:"t"`
	NonceHex      string          `json:"nonce_hex"`
	JSON          string          `json:"json"`
	PaddedLen     int             `json:"padded_len"`
	PaddedHex     string          `json:"padded_hex"`
	CiphertextHex string          `json:"ciphertext_hex"` // ciphertext || 16-byte tag, without the nonce
	SealedB64     string          `json:"sealed_b64"`     // base64std(nonce || ciphertext): FCM data "c"
	Truncated     bool            `json:"truncated"`
	InputBodyLen  int             `json:"input_body_runes,omitempty"`
	FCMRequest    json.RawMessage `json:"fcm_request"`
}

// CodeVector is one input to the code parser.
type CodeVector struct {
	Input     string `json:"input"`
	Valid     bool   `json:"valid"`
	SecretHex string `json:"secret_hex,omitempty"`
	Note      string `json:"note"`
}

// InvalidVector is a sealed payload that a receiver must reject.
type InvalidVector struct {
	Name      string `json:"name"`
	SealedB64 string `json:"sealed_b64"`
	Reason    string `json:"reason"`
}

// VectorSecret is the fixed secret used by the vectors (never use it for real pairing).
var VectorSecret = Secret{0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff}

func nonceFor(i int) []byte {
	n := make([]byte, NonceSize)
	copy(n, "tbd-vector")
	n[NonceSize-1] = byte(i)
	return n
}

// FCMRequest builds the FCM HTTP v1 request body for a sealed payload (BRIEF §3).
func FCMRequest(topic, c, msgType string) []byte {
	ttl := "3600s"
	if msgType == TypeHB {
		ttl = "21600s"
	}
	body := map[string]any{"message": map[string]any{
		"topic":   topic,
		"android": map[string]any{"priority": "high", "ttl": ttl},
		"data":    map[string]string{"c": c},
	}}
	b, err := json.Marshal(body)
	if err != nil {
		panic(err)
	}
	return b
}

// GenerateVectors deterministically builds proto/vectors.json.
func GenerateVectors() Vectors {
	s := VectorSecret
	k := s.Key()
	v := Vectors{
		Comment:     "Generated by `mise run gen-vectors` from internal/proto. Do not edit. Protocol changes require a version bump.",
		Protocol:    "tbd:v1",
		AAD:         AAD,
		SecretHex:   hex.EncodeToString(s[:]),
		Code:        s.Code(),
		DisplayCode: s.DisplayCode(),
		QRText:      s.QRText(),
		KeyHex:      hex.EncodeToString(k[:]),
		Topic:       s.Topic(),
	}
	const ts = 1767225600 // 2026-01-01T00:00:00Z
	long := strings.Repeat("Lorem ipsum dolor sit amet, «quotes» \"escaped\" — ünïcödé 🚀. ", 60)
	msgs := []struct {
		name string
		m    Message
	}{
		{"msg", Message{V: 1, T: TypeMsg, ID: "6f9619ff-8b86-4d01-b42d-00c04fc964ff", TS: ts, Title: "Alice", Body: "hi", URL: "https://teams.microsoft.com/v2/?tbdChat=19%3Aabc%40thread.v2", Tag: "19:abc@thread.v2"}},
		{"msg_unicode", Message{V: 1, T: TypeMsg, ID: "0e6f1c39-5d0a-4b8e-9d55-2f1b8f3c7a10", TS: ts + 1, Title: "Борис <b>&</b>", Body: "line1\nline2\t\"quoted\" \\ emoji 😀  ", URL: "https://teams.microsoft.com/v2/", Tag: "t"}},
		{"msg_long", Message{V: 1, T: TypeMsg, ID: "c1b5a0e2-4f43-4b1e-8f6e-9a7d2b3c4d5e", TS: ts + 2, Title: "Long", Body: long, URL: "https://teams.microsoft.com/v2/", Tag: "19:long@thread.v2"}},
		{"alert_session_expired", Message{V: 1, T: TypeAlert, ID: "1b4e28ba-2fa1-4d2e-883f-0016d3cca427", TS: ts + 3, Title: "Teams session expired", Body: "Run `tbd login` on the computer.", Kind: KindSessionExpired}},
		{"alert_browser_dead", Message{V: 1, T: TypeAlert, ID: "2c5f39cb-3fb2-4e3f-994f-1127e4ddb538", TS: ts + 4, Title: "Browser keeps crashing", Kind: KindBrowserDead}},
		{"alert_daemon_stopping", Message{V: 1, T: TypeAlert, ID: "3d6f4adc-4fc3-4f4f-aa5f-2238f5eec649", TS: ts + 5, Title: "tbd stopped", Kind: KindDaemonStopping}},
		{"hb", Message{V: 1, T: TypeHB, ID: "4e7f5bed-5fd4-4f5f-bb6f-3349f6ffd75a", TS: ts + 6}},
		{"pair", Message{V: 1, T: TypePair, ID: "5f8f6cfe-6fe5-4f6f-8c7f-445af7aae86b", TS: ts + 7}},
	}
	for i, x := range msgs {
		js, sent, err := EncodeJSON(x.m)
		if err != nil {
			panic(err)
		}
		padded, err := Pad(js)
		if err != nil {
			panic(err)
		}
		nonce := nonceFor(i)
		sealed, err := Seal(k, nonce, padded)
		if err != nil {
			panic(err)
		}
		c := base64.StdEncoding.EncodeToString(sealed)
		mv := MessageVector{
			Name: x.name, Type: x.m.T, NonceHex: hex.EncodeToString(nonce), JSON: string(js),
			PaddedLen: len(padded), PaddedHex: hex.EncodeToString(padded),
			CiphertextHex: hex.EncodeToString(sealed[NonceSize:]), SealedB64: c,
			Truncated: sent.Body != x.m.Body, FCMRequest: FCMRequest(v.Topic, c, x.m.T),
		}
		if mv.Truncated {
			mv.InputBodyLen = len([]rune(x.m.Body))
		}
		v.Messages = append(v.Messages, mv)
	}

	code := s.Code()
	lowerDashed := strings.ToLower(s.DisplayCode())
	nonCanonical := code[:CodeLen-1] + "B"
	v.CodeInputs = []CodeVector{
		{Input: code, Valid: true, SecretHex: v.SecretHex, Note: "canonical"},
		{Input: s.DisplayCode(), Valid: true, SecretHex: v.SecretHex, Note: "display form with dashes"},
		{Input: lowerDashed, Valid: true, SecretHex: v.SecretHex, Note: "lowercase with dashes: case is folded"},
		{Input: " " + code[:13] + " " + code[13:] + " ", Valid: true, SecretHex: v.SecretHex, Note: "spaces are ignored"},
		{Input: s.QRText(), Valid: true, SecretHex: v.SecretHex, Note: "QR text"},
		{Input: code[:CodeLen-1], Valid: false, Note: "25 characters"},
		{Input: code + "A", Valid: false, Note: "27 characters"},
		{Input: code[:CodeLen-1] + "1", Valid: false, Note: "'1' is not in the base32 alphabet"},
		{Input: nonCanonical, Valid: false, Note: "non-zero trailing bits in the last character"},
		{Input: "", Valid: false, Note: "empty"},
	}

	// Payloads that authenticate but must still be rejected, plus a forgery.
	seal := func(i int, padded []byte) string {
		sealed, err := Seal(k, nonceFor(i), padded)
		if err != nil {
			panic(err)
		}
		return base64.StdEncoding.EncodeToString(sealed)
	}
	good, _ := Pad([]byte(v.Messages[0].JSON))
	nonZero := bytes.Clone(good)
	nonZero[len(nonZero)-1] = 1
	badLen := bytes.Clone(good)
	binary.BigEndian.PutUint16(badLen, SmallPad)
	smallInLarge := make([]byte, LargePad)
	copy(smallInLarge, good)
	notJSON, _ := Pad([]byte("not json"))
	wrongVersion, _ := Pad([]byte(strings.Replace(v.Messages[0].JSON, `"v":1`, `"v":2`, 1)))
	wrongType, _ := Pad([]byte(strings.Replace(v.Messages[0].JSON, `"t":"msg"`, `"t":"cmd"`, 1)))
	odd := make([]byte, 1000)
	binary.BigEndian.PutUint16(odd, 2)
	copy(odd[2:], "{}")
	tampered, _ := base64.StdEncoding.DecodeString(v.Messages[0].SealedB64)
	tampered[NonceSize+5] ^= 0x01
	v.Invalid = []InvalidVector{
		{Name: "nonzero_padding", SealedB64: seal(100, nonZero), Reason: "padding bytes must be zero"},
		{Name: "length_overflow", SealedB64: seal(101, badLen), Reason: "declared length exceeds the buffer"},
		{Name: "small_in_large", SealedB64: seal(102, smallInLarge), Reason: "a document that fits 1024 must not use 2048"},
		{Name: "not_json", SealedB64: seal(103, notJSON), Reason: "plaintext is not JSON"},
		{Name: "wrong_version", SealedB64: seal(104, wrongVersion), Reason: "v must be 1"},
		{Name: "unknown_type", SealedB64: seal(105, wrongType), Reason: "t must be msg, alert, hb or pair"},
		{Name: "odd_size", SealedB64: seal(106, odd), Reason: "padded size must be 1024 or 2048"},
		{Name: "tampered", SealedB64: base64.StdEncoding.EncodeToString(tampered), Reason: "Poly1305 tag does not verify"},
	}
	return v
}

// MarshalVectors renders vectors.json exactly as committed.
func MarshalVectors(v Vectors) []byte {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		panic(err)
	}
	return buf.Bytes()
}
