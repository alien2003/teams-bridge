// launchd (macOS, D26): a LaunchAgent ~/Library/LaunchAgents/<name>.plist with the label <name>,
// loaded into the user's GUI domain gui/<uid>. Its keys mirror the systemd unit: start at login
// (RunAtLoad), restart after a crash or an error exit but not after a clean stop
// (KeepAlive.SuccessfulExit = false, restarts at most every ThrottleInterval seconds), SIGTERM and
// then SIGKILL after ExitTimeOut seconds (= TimeoutStopSec).

// LaunchdThrottle is ThrottleInterval: launchd starts the job again at most this often.
const LaunchdThrottle = 10

// LaunchdExitTimeout is ExitTimeOut: how long launchd waits after SIGTERM before SIGKILL. It covers
// the daemon's own shutdown (daemon_stopping, the browser's close).
const LaunchdExitTimeout = 30

// StderrLog is launchd's file for the daemon's stdout and stderr inside the data directory: it
// gets only what happens before the log file is open (panics, a bad command line). The log
// itself is tbd.log (--log-file), which tbd rotates; launchd rotates nothing.
const StderrLog = "tbd.stderr.log"

// ErrNoGUIDomain means launchd has no GUI domain for the user: nobody is logged in at the Mac's
// screen (an SSH session alone has none), so a LaunchAgent cannot be loaded now.
var ErrNoGUIDomain = errors.New("service: launchd has no GUI domain for this user (log in at the Mac itself)")

// unloadPoll and unloadWait pace unloadJob (variables for tests).
var (
	unloadPoll = 250 * time.Millisecond
	unloadWait = 40 * time.Second
)

func launchctl(args ...string) []string { return append([]string{"launchctl"}, args...) }

func launchdDomain(env Env) (string, error) {
	switch {
	case env.UID == 0:
		return "", errors.New("service: refusing to manage launchd jobs as root: run tbd install as yourself, not with sudo")
	case env.UID < 0:
		return "", errors.New("service: unknown user id")
	}
	return "gui/" + strconv.Itoa(env.UID), nil
}

// LaunchdTarget is the launchd service target gui/<uid>/<name>.
func LaunchdTarget(name string, env Env) (string, error) {
	s, err := Spec{Name: name}.normalize("darwin", false)
	if err != nil {
		return "", err
	}
	d, err := launchdDomain(env)
	if err != nil {
		return "", err
	}
	return d + "/" + s.Name, nil
}

// LaunchAgentsDir is env.LaunchAgentsDir, else <HomeDir>/Library/LaunchAgents.
func LaunchAgentsDir(env Env) (string, error) {
	if env.LaunchAgentsDir != "" {
		if !strings.HasPrefix(env.LaunchAgentsDir, "/") {
			return "", fmt.Errorf("service: LaunchAgents directory %q is not absolute", env.LaunchAgentsDir)
		}
		return env.LaunchAgentsDir, nil
	}
	if !strings.HasPrefix(env.HomeDir, "/") {
		return "", errors.New("service: cannot find the home directory for ~/Library/LaunchAgents")
	}
	return path.Join(env.HomeDir, "Library", "LaunchAgents"), nil
}

// PlistFile is the LaunchAgent's plist for spec.
func PlistFile(spec Spec, env Env) (string, error) {
	s, err := spec.normalize("darwin", false)
	if err != nil {
		return "", err
	}
	dir, err := LaunchAgentsDir(env)
	if err != nil {
		return "", err
	}
	return path.Join(dir, s.Name+".plist"), nil
}

// LaunchdPlist renders the LaunchAgent property list (XML) for spec, which needs Home.
//
// Not in it, on purpose: EnvironmentVariables (tbd needs none: --home is on the command line, and
// the browser is found in /Applications) and WorkingDirectory (launchd's default, /, is fine).
// ProcessType Interactive exempts the daemon from App Nap-style CPU, I/O and timer throttling, as
// notification latency is the product; LimitLoadToSessionType Aqua keeps it in the GUI session,
// where the user's login and keychain are; Umask 63 (077) keeps everything it creates private.
func LaunchdPlist(spec Spec) (string, error) {
	s, err := spec.normalize("darwin", true)
	if err != nil {
		return "", err
	}
	if s.Home == "" {
		return "", errors.New("service: a LaunchAgent needs the data directory (Home) for its log files")
	}
	argv := append([]string{s.Exe}, s.Args()...)
	for _, a := range argv {
		if !utf8.ValidString(a) {
			return "", fmt.Errorf("service: argument %q is not valid UTF-8, which a property list cannot hold", a)
		}
	}
	stdio := path.Join(s.Home, StderrLog)
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	b.WriteString(`<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">` + "\n")
	b.WriteString("<!-- Generated by tbd install; tbd uninstall removes it. -->\n")
	b.WriteString(`<plist version="1.0">` + "\n<dict>\n")
	key := func(k string) { fmt.Fprintf(&b, "\t<key>%s</key>\n", k) }
	str := func(indent, v string) { fmt.Fprintf(&b, "%s<string>%s</string>\n", indent, xmlEscape(v)) }
	integer := func(k string, v int) { key(k); fmt.Fprintf(&b, "\t<integer>%d</integer>\n", v) }
	key("Label")
	str("\t", s.Name)
	key("ProgramArguments")
	b.WriteString("\t<array>\n")
	for _, a := range argv {
		str("\t\t", a)
	}
	b.WriteString("\t</array>\n")
	key("RunAtLoad")
	b.WriteString("\t<true/>\n")
	key("KeepAlive")
	b.WriteString("\t<dict>\n\t\t<key>SuccessfulExit</key>\n\t\t<false/>\n\t</dict>\n")
	integer("ThrottleInterval", LaunchdThrottle)
	integer("ExitTimeOut", LaunchdExitTimeout)
	key("ProcessType")
	str("\t", "Interactive")
	key("LimitLoadToSessionType")
	str("\t", "Aqua")
	integer("Umask", 0o077)
	key("StandardOutPath")
	str("\t", stdio)
	key("StandardErrorPath")
	str("\t", stdio)
	b.WriteString("</dict>\n</plist>\n")
	return b.String(), nil
}

func darwinInstall(s Spec, env Env) (Plan, error) {
	if s.Home == "" {
		return Plan{}, errors.New("service: install on darwin needs the data directory (Home)")
	}
	target, err := LaunchdTarget(s.Name, env)
	if err != nil {
		return Plan{}, err
	}
	domain, _ := launchdDomain(env)
	plist, err := LaunchdPlist(s)
	if err != nil {
		return Plan{}, err
	}
	file, err := PlistFile(s, env)
	if err != nil {
		return Plan{}, err
	}
	p := Plan{
		OS: "darwin",
		// launchd opens StandardErrorPath before it starts tbd, and creates no directory for it.
		Dirs:  []string{s.Home},
		Files: []File{{Path: file, Content: []byte(plist), Mode: 0o644}},
	}
	// enable: a job someone disabled (`launchctl disable`) would otherwise refuse to load, now and
	// at every login. It starts nothing.
	p.Commands = [][]string{launchctl("enable", target)}
	logs := fmt.Sprintf("logs: %s (early errors: %s)", path.Join(s.Home, "tbd.log"), path.Join(s.Home, StderrLog))
	if s.NoStart {
		p.Notes = append(p.Notes, fmt.Sprintf("LaunchAgent %s starts tbd at your next login (%s); install does not start it now (tbd start).\nL%s", s.Name, domain, logs[1:]))
	} else {
		// Unload first: bootstrap fails while an old definition is loaded, and a re-install must run
		// the new plist and binary (the running daemon gets SIGTERM and stops gracefully).
		p.Unload = []string{target}
		p.Commands = append(p.Commands, launchctl("bootstrap", domain, file))
		p.Notes = append(p.Notes, fmt.Sprintf("LaunchAgent %s starts tbd at every login (%s); install also (re)starts it now.\nStatus: launchctl print %s; %s; stop: tbd stop; start again: tbd start", s.Name, domain, target, logs))
	}
	p.Notes = append(p.Notes, "macOS may say \"Background Items Added\": tbd runs only while it is allowed in the background\n"+
		"(System Settings > General > Login Items & Extensions). It needs you logged in, and the Mac awake.")
	if env.Quarantined != nil && env.Quarantined(s.Exe) {
		p.Notes = append(p.Notes, fmt.Sprintf("%s carries com.apple.quarantine (downloaded with a browser): Gatekeeper refuses\n"+
			"this unsigned binary until you allow it. Run once: xattr -d com.apple.quarantine %s", s.Exe, shQuote(s.Exe)))
	}
	return p, nil
}

func darwinUninstall(s Spec, env Env) (Plan, error) {
	target, err := LaunchdTarget(s.Name, env)
	if err != nil {
		return Plan{}, err
	}
	file, err := PlistFile(s, env)
	if err != nil {
		return Plan{}, err
	}
	return Plan{OS: "darwin", Unload: []string{target}, RemoveFiles: []string{file}, BestEffort: true}, nil
}

// unloadJob boots target out when launchd has it loaded and waits, up to unloadWait, until launchd
// has removed it. bootout's own exit status is advisory (it reports, for example, a job that went
// away by itself meanwhile); what counts is that `launchctl print` no longer finds the job, since
// a bootstrap issued while the removal is still pending fails with an I/O error.
func unloadJob(ctx context.Context, r Runner, goos, target string, out func(string)) error {
	if _, err := r.Run(ctx, "launchctl", "print", target); err != nil {
		return nil // not loaded
	}
	c := launchctl("bootout", target)
	line := quoteCommand(goos, c)
	out("Running: " + line)
	o, berr := r.Run(ctx, c[0], c[1:]...)
	if text := strings.TrimSpace(o); text != "" {
		out("  " + strings.ReplaceAll(text, "\n", "\n  "))
	}
	deadline := time.Now().Add(unloadWait)
	for {
		if _, err := r.Run(ctx, "launchctl", "print", target); err != nil {
			return nil
		}
		if time.Now().After(deadline) {
			return fmt.Errorf("%s: %s is still loaded after %s (bootout: %v)", line, target, unloadWait, berr)
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(unloadPoll):
		}
	}
}

// LaunchdJob is what `launchctl print gui/<uid>/<name>` says about a job.
type LaunchdJob struct {
	Loaded   bool
	State    string // "running", "not running", …
	PID      int    // 0 when not running
	Runs     int
	LastExit string // "0", "1", "(never exited)", …
}

// QueryLaunchd asks launchd about the job name in the user's GUI domain. A job that is not loaded
// is Loaded false; a missing GUI domain is ErrNoGUIDomain.
func QueryLaunchd(ctx context.Context, r Runner, name string, env Env) (LaunchdJob, error) {
	if r == nil {
		r = ExecRunner{}
	}
	target, err := LaunchdTarget(name, env)
	if err != nil {
		return LaunchdJob{}, err
	}
	out, err := r.Run(ctx, "launchctl", "print", target)
	if err == nil {
		job := parseLaunchdPrint(out)
		job.Loaded = true
		return job, nil
	}
	domain, _ := launchdDomain(env)
	if dout, derr := r.Run(ctx, "launchctl", "print", domain); derr != nil {
		return LaunchdJob{}, fmt.Errorf("%w: launchctl print %s: %v: %s", ErrNoGUIDomain, domain, derr, firstLine(dout))
	}
	return LaunchdJob{}, nil
}

func firstLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	return s
}

// parseLaunchdPrint reads the job's own properties from `launchctl print` output: the
// "key = value" lines directly inside the outer braces. Nested blocks ("arguments = {", endpoints,
// event triggers …) are skipped, since they repeat key names such as "state". The format is
// documented as unstable, so anything unrecognised is ignored.
func parseLaunchdPrint(out string) LaunchdJob {
	var job LaunchdJob
	depth := 0
	for _, ln := range strings.Split(out, "\n") {
		t := strings.TrimSpace(ln)
		switch {
		case strings.HasSuffix(t, "{"):
			depth++
			continue
		case t == "}" || strings.HasPrefix(t, "}"):
			depth--
			continue
		}
		if depth != 1 {
			continue
		}
		k, v, ok := strings.Cut(t, " = ")
		if !ok {
			continue
		}
		switch k {
		case "state":
			job.State = v
		case "pid":
			if n, err := strconv.Atoi(v); err == nil && n > 0 {
				job.PID = n
			}
		case "runs":
			job.Runs, _ = strconv.Atoi(v)
		case "last exit code":
			job.LastExit = v
		}
	}
	return job
}

// LaunchdBootout is the command that stops and unloads the job: launchd sends SIGTERM, then
// SIGKILL after ExitTimeOut, and never restarts a job whose removal is pending. The job stays
// unloaded until `tbd start` or the next login.
func LaunchdBootout(target string) []string { return launchctl("bootout", target) }

// LaunchdStatus is the one-line launchd state for `tbd status` on macOS.
func LaunchdStatus(ctx context.Context, r Runner, name string, env Env) string {
	target, err := LaunchdTarget(name, env)
	if err != nil {
		return err.Error()
	}
	if err := CheckInstalled(ctx, r, name, "darwin", env); errors.Is(err, ErrNotInstalled) {
		return "not installed (tbd install)"
	} else if err != nil {
		return err.Error()
	}
	job, err := QueryLaunchd(ctx, r, name, env)
	switch {
	case err != nil:
		return "installed, state unknown: " + err.Error()
	case !job.Loaded:
		return target + " installed, not loaded (tbd start)"
	case job.PID > 0:
		return fmt.Sprintf("%s loaded, running (pid %d)", target, job.PID)
	case job.LastExit != "":
		return fmt.Sprintf("%s loaded, not running (last exit code %s)", target, job.LastExit)
	}
	return target + " loaded, not running"
}
