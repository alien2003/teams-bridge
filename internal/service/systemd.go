// SystemdUnit renders the systemd user unit for spec (Linux).
//
// Not in the unit, on purpose: After=/Wants=network-online.target. A user manager cannot see
// system units (network-online.target is "not-found" there), so both would be no-ops; the daemon
// copes with a missing network through its own retry loop.
func SystemdUnit(spec Spec) (string, error) {
	s, err := spec.normalize("linux", true)
	if err != nil {
		return "", err
	}
	if strings.HasSuffix(s.Description, `\`) {
		return "", errors.New("service: description must not end in a backslash (systemd line continuation)")
	}
	words := []string{systemdQuote(s.Exe)}
	for _, a := range s.Args() {
		words = append(words, systemdQuote(a))
	}
	var b strings.Builder
	b.WriteString("# Generated by `tbd install`; `tbd uninstall` removes it.\n")
	b.WriteString("[Unit]\n")
	fmt.Fprintf(&b, "Description=%s\n", strings.ReplaceAll(s.Description, "%", "%%"))
	fmt.Fprintf(&b, "Documentation=%s\n", ProjectURL)
	b.WriteString("\n[Service]\n")
	// exec: a missing or non-executable binary fails the start instead of looking "active".
	b.WriteString("Type=exec\n")
	fmt.Fprintf(&b, "ExecStart=%s\n", strings.Join(words, " "))
	b.WriteString("Restart=always\n")
	b.WriteString("RestartSec=10\n")
	// SIGTERM only to tbd, which then sends daemon_stopping and closes the browser itself; whatever
	// is left after TimeoutStopSec is killed. With the default control-group mode the browser would
	// die at the same instant and race the shutdown with a browser_dead alert.
	b.WriteString("KillMode=mixed\n")
	b.WriteString("TimeoutStopSec=30\n")
	b.WriteString("\n[Install]\n")
	b.WriteString("WantedBy=default.target\n")
	return b.String(), nil
}

// systemdQuote quotes one word of an Exec*= line: specifiers ('%') and environment variable
// references ('$') are escaped by doubling; words with blanks, quotes, backslashes or ';' (or
// empty ones) are double-quoted with C-style escapes for '\' and '"'.
func systemdQuote(s string) string {
	s = strings.ReplaceAll(s, "%", "%%")
	s = strings.ReplaceAll(s, "$", "$$")
	if s != "" && !strings.ContainsAny(s, " \t\"'\\;") {
		return s
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// UserUnitDir is the directory for persistent user units, evaluated the way the systemd user
// manager does it: $XDG_CONFIG_HOME/systemd/user if that is an absolute path, else
// $HOME/.config/systemd/user. The manager's environment (Env.ManagerEnv) wins over the
// installer's when known: an XDG_CONFIG_HOME set only in a shell (or by mise) is invisible to the
// manager, and a unit written there would never be found.
func UserUnitDir(env Env) (string, error) {
	get, home := env.getenv, env.HomeDir
	if env.ManagerEnv != nil {
		get = func(k string) string { return env.ManagerEnv[k] }
		if h := env.ManagerEnv["HOME"]; strings.HasPrefix(h, "/") {
			home = h
		}
	}
	if x := get("XDG_CONFIG_HOME"); strings.HasPrefix(x, "/") {
		return path.Join(x, "systemd", "user"), nil
	}
	if !strings.HasPrefix(home, "/") {
		return "", errors.New("service: cannot find the home directory for the systemd user unit")
	}
	return path.Join(home, ".config", "systemd", "user"), nil
}

// UnitFile is the path of the user unit file for spec.
func UnitFile(spec Spec, env Env) (string, error) {
	s, err := spec.normalize("linux", false)
	if err != nil {
		return "", err
	}
	dir, err := UserUnitDir(env)
	if err != nil {
		return "", err
	}
	return path.Join(dir, s.Name+".service"), nil
}

func systemctl(args ...string) []string { return append([]string{"systemctl", "--user"}, args...) }

func linuxInstall(s Spec, env Env) (Plan, error) {
	unit, err := SystemdUnit(s)
	if err != nil {
		return Plan{}, err
	}
	file, err := UnitFile(s, env)
	if err != nil {
		return Plan{}, err
	}
	unitName := s.Name + ".service"
	p := Plan{OS: "linux", Files: []File{{Path: file, Content: []byte(unit), Mode: 0o644}}}
	if s.Runtime {
		p.Commands = [][]string{
			systemctl("--runtime", "link", file),
			systemctl("daemon-reload"),
			systemctl("--runtime", "enable", unitName),
		}
		return p, nil
	}
	// daemon-reload first: when the unit already exists and is enabled, enable changes nothing and
	// does not reload, and restart would run the old definition.
	p.Commands = [][]string{systemctl("daemon-reload"), systemctl("enable", unitName)}
	if s.NoStart {
		p.Notes = append(p.Notes, fmt.Sprintf("%s starts with your user session; install does not start it now (systemctl --user start %s).", unitName, unitName))
	} else {
		// restart, not start: a re-install picks up the new unit and binary.
		p.Commands = append(p.Commands, systemctl("restart", unitName))
		p.Notes = append(p.Notes, fmt.Sprintf("%s starts with your user session; install also (re)starts it now.\nStatus: systemctl --user status %s; logs: journalctl --user -u %s -f", unitName, unitName, unitName))
	}
	if wsl, distro := detectWSL(env); wsl {
		p.Notes = append(p.Notes, wslInstallNote(s, env, distro))
	} else {
		p.Notes = append(p.Notes, fmt.Sprintf("To run it without a login session (headless machine): loginctl enable-linger %s", lingerUser(env)))
	}
	return p, nil
}

func linuxUninstall(s Spec, env Env) (Plan, error) {
	file, err := UnitFile(s, env)
	if err != nil {
		return Plan{}, err
	}
	unitName := s.Name + ".service"
	p := Plan{OS: "linux", RemoveFiles: []string{file}, PostCommands: [][]string{systemctl("daemon-reload")}, BestEffort: true}
	if s.Runtime {
		// --runtime disable removes both the default.target.wants link and the link itself.
		p.Commands = [][]string{systemctl("--runtime", "disable", unitName)}
		return p, nil
	}
	p.Commands = [][]string{systemctl("disable", "--now", unitName)}
	if wsl, _ := detectWSL(env); wsl {
		p.Notes = append(p.Notes, wslUninstallNote(s, env))
	}
	return p, nil
}

// detectWSL reports whether the installer runs inside WSL and the distribution name if known.
func detectWSL(env Env) (bool, string) {
	if d := env.getenv("WSL_DISTRO_NAME"); d != "" {
		return true, d
	}
	if env.ReadFile != nil {
		if b, err := env.ReadFile("/proc/sys/kernel/osrelease"); err == nil && strings.Contains(strings.ToLower(string(b)), "microsoft") {
			return true, ""
		}
	}
	return false, ""
}

var distroRE = regexp.MustCompile(`^[A-Za-z0-9._-]+$`)

// lingerUser is the user argument for loginctl, shell-quoted; "$USER" (expanded by the shell)
// when the environment does not name the user.
func lingerUser(env Env) string {
	for _, k := range []string{"USER", "LOGNAME"} {
		if v := env.getenv(k); v != "" {
			return shQuote(v)
		}
	}
	return `"$USER"`
}

// KeepAliveTaskName is the Windows logon task that keeps the WSL distribution running.
func KeepAliveTaskName(spec Spec) string {
	n := spec.Name
	if n == "" {
		n = DefaultName
	}
	return n + "-wsl"
}

func wslInstallNote(s Spec, env Env, distro string) string {
	d, unknown := distro, ""
	if !distroRE.MatchString(d) {
		d, unknown = "<distro>", " Replace <distro> with the name `wsl.exe -l -v` shows."
	}
	task := KeepAliveTaskName(s)
	var b strings.Builder
	b.WriteString("WSL: Windows does not boot this distribution at logon, and WSL stops it ~15 s after the last\n")
	b.WriteString("wsl.exe client exits (systemd services do not count). To keep tbd running:\n")
	fmt.Fprintf(&b, "1. Here, once: loginctl enable-linger %s\n", lingerUser(env))
	b.WriteString("   (your systemd user manager, and " + s.Name + ".service with it, then starts whenever the distribution boots)\n")
	b.WriteString("2. In Windows PowerShell, unelevated: a logon task that boots the distribution and keeps it alive.\n")
	b.WriteString("   It runs only `sleep infinity`, so systemd stays the only supervisor of tbd (two daemons would fight\n")
	b.WriteString("   over one browser profile). Trigger and principal name only you, so no elevation is needed." + unknown + "\n")
	fmt.Fprintf(&b, "   $u = \"$env:USERDOMAIN\\$env:USERNAME\"; Register-ScheduledTask -TaskName '%s' -Force"+
		" -Action (New-ScheduledTaskAction -Execute \"$env:SystemRoot\\System32\\conhost.exe\" -Argument '--headless wsl.exe -d %s --exec sleep infinity')"+
		" -Trigger (New-ScheduledTaskTrigger -AtLogOn -User $u)"+
		" -Principal (New-ScheduledTaskPrincipal -UserId $u -LogonType Interactive -RunLevel Limited)"+
		" -Settings (New-ScheduledTaskSettingsSet -ExecutionTimeLimit ([TimeSpan]::Zero) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -RestartCount 255 -RestartInterval (New-TimeSpan -Minutes 1));"+
		" Start-ScheduledTask -TaskName '%s'\n", task, d, task)
	b.WriteString("3. Optional fallback, in %UserProfile%\\.wslconfig (all distributions; recent WSL; after wsl --shutdown):\n")
	b.WriteString("   [general]\n")
	b.WriteString("   instanceIdleTimeout=-1\n")
	b.WriteString("   keeps the distribution up even with no wsl.exe client. ([wsl2] vmIdleTimeout does not help: it only\n")
	b.WriteString("   applies once no distribution is running.)")
	return b.String()
}

func wslUninstallNote(s Spec, env Env) string {
	return fmt.Sprintf("WSL: also remove the Windows keep-alive task, in PowerShell: Unregister-ScheduledTask -TaskName '%s' -Confirm:$false\n"+
		"and, unless something else needs it: loginctl disable-linger %s", KeepAliveTaskName(s), lingerUser(env))
}

// SystemdManagerEnv returns the environment of the systemd user manager
// (`systemctl --user show-environment`); an error means the manager is not reachable.
func SystemdManagerEnv(ctx context.Context, r Runner) (map[string]string, error) {
	if r == nil {
		r = ExecRunner{}
	}
	out, err := r.Run(ctx, "systemctl", "--user", "show-environment")
	if err != nil {
		return nil, fmt.Errorf("systemctl --user show-environment: %w: %s", err, strings.TrimSpace(out))
	}
	return parseManagerEnv(out), nil
}

// parseManagerEnv parses show-environment output: KEY=VALUE lines, where newer systemd prints
// values with special characters as $'...' (ANSI-C quoting).
func parseManagerEnv(out string) map[string]string {
	m := map[string]string{}
	sc := bufio.NewScanner(strings.NewReader(out))
	for sc.Scan() {
		k, v, ok := strings.Cut(sc.Text(), "=")
		if !ok || k == "" {
			continue
		}
		if strings.HasPrefix(v, "$'") && strings.HasSuffix(v, "'") && len(v) >= 3 {
			v = unquoteANSIC(v[2 : len(v)-1])
		}
		m[k] = v
	}
	return m
}

func unquoteANSIC(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c != '\\' || i+1 == len(s) {
			b.WriteByte(c)
			continue
		}
		i++
		switch s[i] {
		case 'n':
			b.WriteByte('\n')
		case 't':
			b.WriteByte('\t')
		case 'r':
			b.WriteByte('\r')
		default: // \\ \' \" and anything else: the character itself
			b.WriteByte(s[i])
		}
	}
	return b.String()
}

// unitFileStates are the answers of `systemctl is-enabled`.
var unitFileStates = map[string]bool{
	"enabled": true, "enabled-runtime": true, "linked": true, "linked-runtime": true, "alias": true,
	"masked": true, "masked-runtime": true, "static": true, "indirect": true, "disabled": true,
	"generated": true, "transient": true, "bad": true, "not-found": true,
}

// UnitState runs `systemctl --user is-enabled <name>.service` and returns its answer (e.g.
// "enabled", "enabled-runtime", "disabled", "not-found"). is-enabled exits non-zero for most
// states; that is not an error here, only an unrecognisable answer is.
func UnitState(ctx context.Context, r Runner, name string) (string, error) {
	if r == nil {
		r = ExecRunner{}
	}
	out, err := r.Run(ctx, "systemctl", "--user", "is-enabled", name+".service")
	words := strings.Fields(out)
	if len(words) > 0 && unitFileStates[words[len(words)-1]] {
		return words[len(words)-1], nil
	}
	if err == nil {
		err = errors.New("unrecognised answer")
	}
	return "", fmt.Errorf("systemctl --user is-enabled %s.service: %w: %s", name, err, strings.TrimSpace(out))
}
