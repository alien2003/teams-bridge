func TestSystemdQuote(t *testing.T) {
	for in, want := range map[string]string{
		"/usr/bin/tbd":     "/usr/bin/tbd",
		"/a b/tbd":         `"/a b/tbd"`,
		"":                 `""`,
		"100%":             "100%%",
		"$HOME":            "$$HOME",
		"${X} y":           `"$${X} y"`,
		`a\b`:              `"a\\b"`,
		`a"b`:              `"a\"b"`,
		"a'b":              `"a'b"`,
		";":                `";"`,
		"--home=/x/y":      "--home=/x/y",
		`C:\Program Files`: `"C:\\Program Files"`,
	} {
		if got := systemdQuote(in); got != want {
			t.Errorf("systemdQuote(%q) = %s, want %s", in, got, want)
		}
	}
}

func TestUserUnitDir(t *testing.T) {
	for _, tc := range []struct {
		name string
		env  Env
		want string
	}{
		{"default", envOf(nil), "/home/u/.config/systemd/user"},
		{"xdg", envOf(map[string]string{"XDG_CONFIG_HOME": "/x/cfg"}), "/x/cfg/systemd/user"},
		{"relative xdg ignored", envOf(map[string]string{"XDG_CONFIG_HOME": "cfg"}), "/home/u/.config/systemd/user"},
		{"manager env wins", Env{Getenv: envOf(map[string]string{"XDG_CONFIG_HOME": "/repo/.xdg/config"}).Getenv, HomeDir: "/home/u", ManagerEnv: map[string]string{"HOME": "/home/u"}}, "/home/u/.config/systemd/user"},
		{"manager xdg", Env{HomeDir: "/home/u", ManagerEnv: map[string]string{"XDG_CONFIG_HOME": "/m/cfg"}}, "/m/cfg/systemd/user"},
		{"manager home", Env{HomeDir: "/home/u", ManagerEnv: map[string]string{"HOME": "/home/other"}}, "/home/other/.config/systemd/user"},
	} {
		got, err := UserUnitDir(tc.env)
		if err != nil || got != tc.want {
			t.Errorf("%s: UserUnitDir = %q, %v; want %q", tc.name, got, err, tc.want)
		}
	}
	if _, err := UserUnitDir(Env{}); err == nil {
		t.Error("no home: no error")
	}
}

func cmdLines(cs [][]string) []string {
	var out []string
	for _, c := range cs {
		out = append(out, strings.Join(c, " "))
	}
	return out
}

func equalLines(t *testing.T, what string, got, want []string) {
	t.Helper()
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("%s:\n got %q\nwant %q", what, got, want)
	}
}

func TestLinuxPlans(t *testing.T) {
	env := envOf(map[string]string{"USER": "alice"})
	spec := Spec{Exe: "/usr/local/bin/tbd", Home: "/home/u/.local/share/tbd"}
	p, err := InstallPlan(spec, "linux", env)
	if err != nil {
		t.Fatal(err)
	}
	if p.OS != "linux" || len(p.Files) != 1 || p.Files[0].Path != "/home/u/.config/systemd/user/tbd.service" || p.Files[0].Mode != 0o644 {
		t.Fatalf("files: %+v", p.Files)
	}
	unit, _ := SystemdUnit(spec)
	if string(p.Files[0].Content) != unit {
		t.Error("file content is not SystemdUnit(spec)")
	}
	equalLines(t, "install commands", cmdLines(p.Commands), []string{
		"systemctl --user daemon-reload",
		"systemctl --user enable tbd.service",
		"systemctl --user restart tbd.service",
	})
	if p.BestEffort || len(p.RemoveFiles) != 0 || len(p.PostCommands) != 0 {
		t.Errorf("unexpected install plan parts: %+v", p)
	}
	if n := strings.Join(p.Notes, "\n"); strings.Contains(n, "WSL") || !strings.Contains(n, "loginctl enable-linger alice") {
		t.Errorf("non-WSL notes: %q", n)
	}

	spec.NoStart = true
	p, _ = InstallPlan(spec, "linux", env)
	equalLines(t, "no-start commands", cmdLines(p.Commands), []string{"systemctl --user daemon-reload", "systemctl --user enable tbd.service"})

	u, err := UninstallPlan(Spec{}, "linux", env)
	if err != nil {
		t.Fatal(err)
	}
	equalLines(t, "uninstall commands", cmdLines(u.Commands), []string{"systemctl --user disable --now tbd.service"})
	equalLines(t, "uninstall removes", u.RemoveFiles, []string{"/home/u/.config/systemd/user/tbd.service"})
	equalLines(t, "uninstall post", cmdLines(u.PostCommands), []string{"systemctl --user daemon-reload"})
	if !u.BestEffort || len(u.Files) != 0 {
		t.Errorf("uninstall plan: %+v", u)
	}
}

func TestLinuxRuntimePlans(t *testing.T) {
	env := envOf(map[string]string{"XDG_CONFIG_HOME": "/r/.xdg/config", "WSL_DISTRO_NAME": "Ubuntu"})
	spec := Spec{Name: "tbd-test-x", Exe: "/bin/true", Runtime: true}
	p, err := InstallPlan(spec, "linux", env)
	if err != nil {
		t.Fatal(err)
	}
	f := "/r/.xdg/config/systemd/user/tbd-test-x.service"
	if p.Files[0].Path != f {
		t.Fatalf("path %s", p.Files[0].Path)
	}
	equalLines(t, "runtime install", cmdLines(p.Commands), []string{
		"systemctl --user --runtime link " + f,
		"systemctl --user daemon-reload",
		"systemctl --user --runtime enable tbd-test-x.service",
	})
	for _, c := range p.Commands {
		for _, a := range c {
			if a == "start" || a == "restart" || a == "--now" {
				t.Errorf("runtime plan starts the unit: %v", c)
			}
		}
	}
	if len(p.Notes) != 0 {
		t.Errorf("runtime plan has notes: %q", p.Notes)
	}
	u, _ := UninstallPlan(spec, "linux", env)
	equalLines(t, "runtime uninstall", cmdLines(u.Commands), []string{"systemctl --user --runtime disable tbd-test-x.service"})
	equalLines(t, "runtime removes", u.RemoveFiles, []string{f})
	if _, err := InstallPlan(Spec{Exe: `C:\tbd.exe`, Home: `C:\h`, Runtime: true}, "windows", envOf(map[string]string{"USERNAME": "u"})); err == nil {
		t.Error("Runtime on windows: no error")
	}
}

func TestWSLNotes(t *testing.T) {
	spec := Spec{Exe: "/usr/local/bin/tbd"}
	p, err := InstallPlan(spec, "linux", envOf(map[string]string{"WSL_DISTRO_NAME": "Ubuntu-24.04", "USER": "bob"}))
	if err != nil {
		t.Fatal(err)
	}
	n := strings.Join(p.Notes, "\n")
	for _, want := range []string{
		"loginctl enable-linger bob",
		"Register-ScheduledTask -TaskName 'tbd-wsl'",
		`-Argument '--headless wsl.exe -d Ubuntu-24.04 --exec sleep infinity'`,
		`-Execute "$env:SystemRoot\System32\conhost.exe"`,
		`New-ScheduledTaskTrigger -AtLogOn -User $u`,
		`$u = "$env:USERDOMAIN\$env:USERNAME"`,
		"-LogonType Interactive -RunLevel Limited",
		"-ExecutionTimeLimit ([TimeSpan]::Zero)",
		"-AllowStartIfOnBatteries -DontStopIfGoingOnBatteries",
		"-RestartCount 255",
		"Start-ScheduledTask -TaskName 'tbd-wsl'",
		"[general]\n   instanceIdleTimeout=-1",
	} {
		if !strings.Contains(n, want) {
			t.Errorf("WSL note lacks %q:\n%s", want, n)
		}
	}
	for _, l := range strings.Split(n, "\n") {
		if !strings.Contains(l, "Register-ScheduledTask") {
			continue
		}
		// The one-liner is one line, and the keep-alive never runs tbd itself (systemd does).
		if !strings.Contains(l, "Start-ScheduledTask") {
			t.Errorf("PowerShell command is split over lines: %q", l)
		}
		if strings.Contains(l, "tbd run") || strings.Contains(l, "-- tbd") || strings.Contains(l, "/tbd") {
			t.Errorf("WSL keep-alive runs tbd: %q", l)
		}
	}

	// Detected through /proc without WSL_DISTRO_NAME: placeholder distro.
	env := envOf(map[string]string{"USER": "bob"})
	env.ReadFile = func(name string) ([]byte, error) {
		if name == "/proc/sys/kernel/osrelease" {
			return []byte("6.6.87.2-microsoft-standard-WSL2\n"), nil
		}
		return nil, os.ErrNotExist
	}
	p, _ = InstallPlan(spec, "linux", env)
	if n := strings.Join(p.Notes, "\n"); !strings.Contains(n, "wsl.exe -d <distro> --exec") || !strings.Contains(n, "wsl.exe -l -v") {
		t.Errorf("placeholder note:\n%s", n)
	}
	// Hostile distro name is not pasted into a PowerShell command.
	p, _ = InstallPlan(spec, "linux", envOf(map[string]string{"WSL_DISTRO_NAME": "x'; rm -rf"}))
	if n := strings.Join(p.Notes, "\n"); strings.Contains(n, "rm -rf") {
		t.Errorf("unsafe distro name in note:\n%s", n)
	}
	// Not WSL.
	env.ReadFile = func(string) ([]byte, error) { return []byte("6.8.0-45-generic\n"), nil }
	p, _ = InstallPlan(spec, "linux", env)
	if n := strings.Join(p.Notes, "\n"); strings.Contains(n, "WSL") {
		t.Errorf("non-WSL got WSL note:\n%s", n)
	}
	// Unknown user: the shell expands $USER.
	p, _ = InstallPlan(spec, "linux", envOf(map[string]string{"WSL_DISTRO_NAME": "Ubuntu"}))
	if n := strings.Join(p.Notes, "\n"); !strings.Contains(n, `loginctl enable-linger "$USER"`) {
		t.Errorf("unknown user:\n%s", n)
	}
	u, _ := UninstallPlan(spec, "linux", envOf(map[string]string{"WSL_DISTRO_NAME": "Ubuntu", "USER": "bob"}))
	if n := strings.Join(u.Notes, "\n"); !strings.Contains(n, "Unregister-ScheduledTask -TaskName 'tbd-wsl' -Confirm:$false") || !strings.Contains(n, "loginctl disable-linger bob") {
		t.Errorf("WSL uninstall note:\n%s", n)
	}
}

