// envOf is a hermetic Env: only the given variables, home /home/u, no /proc.
func envOf(vars map[string]string) Env {
	return Env{Getenv: func(k string) string { return vars[k] }, HomeDir: "/home/u"}
}

const goldenUnit = "# Generated by `tbd install`; `tbd uninstall` removes it.\n" +
	"[Unit]\n" +
	"Description=tbd 100%% test\n" +
	"Documentation=https://github.com/alien2003/teams-bridge\n" +
	"\n" +
	"[Service]\n" +
	"Type=exec\n" +
	`ExecStart="/opt/my tools/tbd" run --home "/home/u/data dir" --x=$$HOME "a\"b\\c" "" "semi;colon"` + "\n" +
	"Restart=always\n" +
	"RestartSec=10\n" +
	"KillMode=mixed\n" +
	"TimeoutStopSec=30\n" +
	"\n" +
	"[Install]\n" +
	"WantedBy=default.target\n"

func TestSystemdUnitGolden(t *testing.T) {
	got, err := SystemdUnit(Spec{
		Exe:         "/opt/my tools/tbd",
		Home:        "/home/u/data dir",
		Description: "tbd 100% test",
		ExtraArgs:   []string{"--x=$HOME", `a"b\c`, "", "semi;colon"},
	})
	if err != nil {
		t.Fatal(err)
	}
	if got != goldenUnit {
		t.Errorf("unit mismatch\n--- got\n%s--- want\n%s", got, goldenUnit)
	}
	for _, bad := range []string{"After=network-online.target", "Wants=", "Environment="} {
		if strings.Contains(got, bad) {
			t.Errorf("unit contains %q", bad)
		}
	}
}

