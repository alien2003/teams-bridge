// fakeRunner records commands and answers from a table keyed by the joined command line.
type fakeRunner struct {
	calls []string
	out   map[string]string
	fail  map[string]bool
}

func (f *fakeRunner) Run(_ context.Context, name string, args ...string) (string, error) {
	line := strings.Join(append([]string{name}, args...), " ")
	f.calls = append(f.calls, line)
	if f.fail[line] {
		return f.out[line], errors.New("exit status 1")
	}
	return f.out[line], nil
}

func TestUnitState(t *testing.T) {
	r := &fakeRunner{out: map[string]string{
		"systemctl --user is-enabled a.service": "enabled-runtime\n",
		"systemctl --user is-enabled b.service": "not-found\n",
		"systemctl --user is-enabled c.service": "Failed to connect to bus: No medium found\n",
	}, fail: map[string]bool{"systemctl --user is-enabled b.service": true, "systemctl --user is-enabled c.service": true}}
	if s, err := UnitState(context.Background(), r, "a"); s != "enabled-runtime" || err != nil {
		t.Errorf("a: %q %v", s, err)
	}
	if s, err := UnitState(context.Background(), r, "b"); s != "not-found" || err != nil {
		t.Errorf("b: %q %v", s, err)
	}
	if s, err := UnitState(context.Background(), r, "c"); err == nil || !strings.Contains(err.Error(), "Failed to connect") {
		t.Errorf("c: %q %v", s, err)
	}
}
